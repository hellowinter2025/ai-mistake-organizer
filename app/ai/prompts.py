"""AI 提示词。

两套模板共用同一套字段：支持 JSON 的模型走严格 schema；
不支持 JSON 的模型改用固定分隔标记，便于稳定地做文本解析。

提示词随**学科**变化：数学、物理这类需要公式的学科走 LaTeX 排版规则，
语文、英语、历史等学科走纯文本规则（强行要求 LaTeX 只会让模型把
“《静夜思》”写成 $\\text{《静夜思》}$，反而更难读）。
"""
from __future__ import annotations


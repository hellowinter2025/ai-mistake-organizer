def build_messages(
    image_b64: str,
    *,
    json_mode: bool,
    extra: str = "",
    subject: object = DEFAULT_SUBJECT,
) -> list[dict]:
    subject = normalise_subject(subject)
    system = system_prompt(json_mode, subject)
    template = USER_PROMPT if json_mode else USER_PROMPT_TEXT
    user_text = template.format(subject=subject, extra=extra or "无")
    return [
        {"role": "system", "content": system},
        {
            "role": "user",
            "content": [
                {"type": "text", "text": user_text},
                {
                    "type": "image_url",
                    "image_url": {"url": f"data:image/jpeg;base64,{image_b64}", "detail": "high"},
                },
            ],
        },
    ]



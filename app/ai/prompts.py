FIELDS = [
    "question_text",
    "question_type",
    "answer",
    "error_analysis",
    "solution_fix",
    "solution_alt",
    "knowledge_points",
    "difficulty",
    "confidence",
    "needs_figure",
    "figure_tikz",
    "notes",
]

# 常见学科；界面用 datalist 提供候选，也允许填自定义（如「信息技术」）
SUBJECTS = ["数学", "物理", "化学", "生物", "语文", "英语", "历史", "地理", "政治", "科学"]
# 这些学科用 LaTeX 排公式；其余按纯文本处理
LATEX_SUBJECTS = {"数学", "物理"}
# 化学单独一套：化学式走 mhchem 的 \ce{}，结构式图形走 SMILES（不是 TikZ）
CHEM_SUBJECTS = {"化学"}
DEFAULT_SUBJECT = "数学"


def normalise_subject(raw: object) -> str:
    """把用户填的学科收敛成一个短字符串，空值回落默认学科。"""
    text = str(raw or "").strip().replace("\n", " ").replace("\r", " ")[:20]
    return text or DEFAULT_SUBJECT


def uses_latex(subject: object) -> bool:
    return normalise_subject(subject) in LATEX_SUBJECTS


def uses_chem(subject: object) -> bool:
    return normalise_subject(subject) in CHEM_SUBJECTS


# 英语题给的不是一道题而是**一段内容**（短文改错、语法填空的短文、书面表达习作），
# 任务是按批改痕迹挑错误点，不是转录整题 —— 走专门的错点抽取规则
ENG_KEYWORDS = ("英语", "english")


def uses_english(subject: object) -> bool:
    text = normalise_subject(subject).lower()
    return any(k in text for k in ENG_KEYWORDS)


def schema_hint(subject: object = DEFAULT_SUBJECT) -> str:
    """字段说明随学科变化：只有走 LaTeX 的学科才要求 $...$。"""
    subject = normalise_subject(subject)
    if uses_english(subject):
        # 英语出成「挖空句 + 答案 + 语法点」，可直接当练习用，序号对齐
        return """{
  "question_text": "挖空的错题句：逐条标小序号 (1)(2)(3)，把出错位置换成 _____，其余照抄原文",
  "question_type": "短文改错/语法填空/书面表达/其他",
  "answer": "每个空的正确答案，逐条标同样的小序号，只给答案本身",
  "error_analysis": "对应的关键语法点：逐条标同样的小序号，与 question_text 严格一一对应",
  "solution_fix": "",
  "solution_alt": "",
  "knowledge_points": ["语法点标签1", "语法点标签2"],
  "difficulty": 3,
  "confidence": 0.9,
  "needs_figure": false,
  "figure_tikz": "",
  "notes": "识别不清、批改痕迹含义不确定等需要提醒的地方；没有就填空字符串"
}"""
    if uses_chem(subject):
        formula = r"化学式/方程式用 \ce{} 包裹并放进 $...$，例如 $\ce{H2SO4}$"
    elif uses_latex(subject):
        formula = "LaTeX 公式用 $...$ 包裹"
    else:
        formula = "公式按原样抄写，不用 LaTeX"
    # f-string 里的花括号要转义，所以整行先算好再插值
    if uses_latex(subject):
        fix_desc = (
            "先写一行「方法：<名称>」，再写一行「触发点：<看到什么条件想到它>」，"
            "然后才是纠正后的完整过程；若原思路方向根本不可行，"
            "这几行连同过程一起写进 solution_alt，本字段填空字符串"
        )
    else:
        fix_desc = "若学生原思路方向可行，给出纠正后的完整解题过程；若原思路根本不可行，填空字符串"
    smiles_line = '\n  "smiles": {"苯酚": "Oc1ccccc1"},' if uses_chem(subject) else ""
    flow_line = (
        '\n  "flow": {"steps": [{"name": "铝土矿"}, {"name": "碱浸", "label": "过量 NaOH"}],'
        ' "side": [{"after": 2, "name": "滤渣"}]},'
        if uses_chem(subject)
        else ""
    )
    return f"""{{
  "question_text": "完整题干（含所有选项），{formula}",
  "question_type": "选择题（单选）/选择题（多选）/填空题/解答题/证明题/其他",
  "answer": "最终答案；选择题只写字母、正确项全部写完（单选 B，多选按字母顺序连写如 ACD）；解答题写最终结果并带单位，不要写解题过程；证明题写要证的结论",
  "error_analysis": "学生的错误原因，定位到具体步骤或概念误区",
  "solution_fix": "{fix_desc}",
  "solution_alt": "更优/更本质的解法（更简洁、更通用或揭示本质）；若与 solution_fix 实质相同，填空字符串",
  "knowledge_points": ["知识点1", "知识点2"],
  "difficulty": 3,
  "confidence": 0.9,
  "needs_figure": false,
  "figure_tikz": "",{smiles_line}{flow_line}
  "notes": "识别不清、图形缺失等需要提醒用户的地方；没有就填空字符串"
}}"""


